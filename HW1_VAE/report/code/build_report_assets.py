"""Create publication-sized plots and LaTeX numbers from measured results."""

import csv
import json
from pathlib import Path

from matplotlib.backends.backend_agg import FigureCanvasAgg
from matplotlib.figure import Figure

REPORT = Path(__file__).resolve().parents[1]


def main():
    rows = list(csv.DictReader((REPORT / 'data/history.csv').open()))
    summary = json.loads((REPORT / 'data/run_summary.json').read_text())
    metrics = json.loads((REPORT / 'data/metrics.json').read_text())['metrics']
    fig = Figure(figsize=(5.5, 1.45))
    FigureCanvasAgg(fig)
    axes = fig.subplots(1, 2)
    epochs = [int(row['epoch']) for row in rows]
    for ax, metric, title in zip(axes, ('loss', 'kl'), ('Total objective', 'KL divergence')):
        for split, color in (('train', '#2363a0'), ('val', '#bd5425')):
            ax.plot(epochs, [float(row[f'{split}_{metric}']) for row in rows],
                    label=split.capitalize(), color=color, linewidth=1.3)
        ax.axvline(summary['selected_epoch'], color='#888888', linestyle=':', linewidth=0.8)
        ax.set_title(title, fontsize=9)
        ax.set_xlabel('Epoch', fontsize=8)
        ax.set_ylabel('Nats / image', fontsize=8)
        ax.tick_params(labelsize=7)
        ax.spines[['top', 'right']].set_visible(False)
        ax.legend(fontsize=7, frameon=False, loc='upper right')
    fig.tight_layout(pad=0.4, w_pad=1.3)
    fig.savefig(REPORT / 'figures/training_curves.png', dpi=300)
    commands = {
        'FIDvalue': f"{metrics['fid_pool2048']:.2f}",
        'ISvalue': f"{metrics['inception_score']:.3f}",
        'ISreal': f"{metrics['real_inception_score']:.3f}",
        'ISsplitmean': f"{metrics['is_10split_mean']:.3f}",
        'ISsplitstd': f"{metrics['is_10split_std']:.3f}",
        'ProbFID': f"{metrics['fid_probability1000']:.4f}",
        'SelectedEpoch': str(summary['selected_epoch']),
        'BestVal': f"{summary['selected_val_loss']:,.2f}",
        'TrainFirst': f"{float(summary['first_epoch']['train_loss']):,.2f}",
        'TrainLast': f"{float(summary['last_epoch']['train_loss']):,.2f}",
        'ValLast': f"{float(summary['last_epoch']['val_loss']):,.2f}",
        'ParamCount': f"{summary['num_parameters']:,}",
    }
    (REPORT / 'source/results.tex').write_text(
        '% Generated by code/build_report_assets.py from data/*.json\n' +
        ''.join('\\newcommand{\\' + key + '}{' + value + '}\n' for key, value in commands.items()))
    print('Updated figures/training_curves.png and source/results.tex')


if __name__ == '__main__':
    main()
